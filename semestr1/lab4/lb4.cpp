#include <iostream>
#include <clocale>
#include <cmath>
#include <cstdlib>
#include <ctime>
using namespace std;
int main() 
{
    setlocale(LC_ALL, "Russian");
    const int MAX_SIZE = 100;
    int M[MAX_SIZE];
    int size = 10; // Исходный размер массива
    // Заполнение массива случайными числами от -50 до 49
    for (int i = 0; i < size; i++) {
        M[i] = rand() % 100 - 50;
    }
    // Вывод исходного массива
    cout << "Исходный массив (размер = " << size << "):" << endl;
    for (int i = 0; i < size; i++) {
        cout << M[i] << " ";
    }
    cout << endl;
    // Удаление элементов с индексами, кратными 3 (0, 3, 6, 9)
    for (int i = size - 1; i >= 0; i--) {
        if (i % 3 == 0) {
            for (int j = i; j < size - 1; j++) {
                M[j] = M[j + 1];
            }
            size--;
        }
    }
    // Вывод массива после удаления
    cout << "Массив после удаления элементов c индексами, кратными 3 (размер = " << size << "):" << endl;
    for (int i = 0; i < size; i++) {
        cout << M[i] << " ";
    }
    cout << endl;
    // Вставка после каждого отрицательного элемента значения |M[i] + 1|
    // Условие size < MAX_SIZE добавлено в if, чтобы избежать использования break
    for (int i = 0; i < size; i++) {
        if (M[i] < 0 && size < MAX_SIZE) {
            // Сдвиг элементов вправо для освобождения места
            for (int j = size; j > i + 1; j--) {
                M[j] = M[j - 1];
            }
            // Запись нового значения
            M[i + 1] = abs(M[i] + 1);
            size++; // Увеличиваем размер
            i++;    // Пропускаем вставленный элемент, чтобы не зациклиться
        }
    }
    // Вывод итогового массива
    cout << "Итоговый массив (размер = " << size << "):" << endl;
    for (int i = 0; i < size; i++) {
        cout << M[i] << " ";
    }
    /*
    Исходный массив (размер = 10):
    -9 17 -16 -50 19 -26 28 8 12 14 
    Массив после удаления элементов c индексами, кратными 3 (размер = 6):
    17 -16 19 -26 8 12 
    Итоговый массив (размер = 8):
    17 -16 15 19 -26 25 8 12 
    */
    return 0;
}