#include <iostream>

int main() {
    int a = 10;
    int b = 20;
    int& r = a; // r становится ссылкой для a

    r = b;   // Значение b (20) присваивается переменной a. Теперь a = 20
    r++;     // Переменная a увеличивается на 1. Теперь a = 21
    
    std::cout << a << " " << b << std::endl;
    // Результат: 21 20
    /*
    Ответ на вопрос: Через ссылку r изменяется объект a. 
    Ссылки в C++ жестко связываются с объектом при инициализации, и их нельзя перенацелить на другую переменную. 
    Операция r = b лишь копирует значение из b в a.
    */
    return 0;
}
