#include <iostream>

int main() {
    int a = 12;
    int* ptr = &a;     // ptr указывает на переменную a
    int copy = *ptr;   // В copy записывается значение из a (12)

    (*ptr)++;          // Значение по указателю (переменная a) увеличивается на 1. a = 13
    
    std::cout << a << " " << copy << std::endl;
    // Результат: 13 12
    /* 
    Ответ на вопрос: Различие заключается в выделении памяти и связи с оригиналом:
    - copy — это самостоятельная переменная, хранящая лишь копию значения на момент инициализации. 
    Изменения a или *ptr никак на неё не влияют.
    - *ptr — это операция разыменования, дающая непосредственный доступ к исходной переменной a по её адресу.
    Любое изменение через *ptr меняет саму a.
    */
    return 0;
}