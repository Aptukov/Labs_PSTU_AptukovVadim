#include <iostream>
using namespace std;

int main() {
    int a = 4, b = 9;
    int* p = &a;   // p указывает на a
    int* q = p;    // q указывает на a
    int& r = *p;   // r привязывается к переменной a

    p = &b;        // p теперь указывает на b
    *q += *p;      // a += b  ->  4 + 9 = 13. (a = 13, r = 13)
    *p = r - 3;    // b = a - 3  ->  13 - 3 = 10. (b = 10)
    q = p;         // q теперь тоже указывает на b
    *q += r;       // b += a  ->  10 + 13 = 23. (b = 23)

    cout << a << " " << b << " " << r << endl;
    // Результат работы: 13 23 13
    /*
    Ответы на вопросы:
    - В конце программы указатели p и q указывают на переменную b.
    - r обозначает ссылку на переменную a.
    */
    return 0;
}
