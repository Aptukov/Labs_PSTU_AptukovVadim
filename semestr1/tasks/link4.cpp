#include <iostream>
using namespace std;

int main() {
    int a = 5, b = 8;
    int& r = a;      // r ссылается на a
    int& s = a;      // s ссылается на a
    int copy = a;    // copy = 5 (независимая копия)

    r = b;           // a = b  ->  a = 8
    s += 2;          // a += 2 ->  a = 10
    b = copy;        // b = 5

    cout << a << " " << b << " " << r << " " << s << " " << copy << endl;
    // Результат работы: 10 5 10 10 5
    // Ответ на вопрос: Нет, copy не меняется.
    // Переменная copy выделена в отдельной области памяти и хранит лишь значение 5.
    // Изменения ссылок r и s влияют исключительно на переменную a.

    return 0;
}
